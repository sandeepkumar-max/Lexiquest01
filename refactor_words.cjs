// Simple regex to extract words from { word: "..." }
function getExistingWords(content) {
  const words = new Set();
  const regex = /word:\s*["']([^"']+)["']/g;
  let match;
  while ((match = regex.exec(content)) !== null) {
    words.add(match[1].toLowerCase());
  }
  return words;
}

